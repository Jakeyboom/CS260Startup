const ConsoleEvent = {
    ACCOUNT_CREATED: 'ACCOUNT_CREATED',
    CLASS_CREATED: 'CLASS_CREATED',
    ASSIGNMENT_CREATED: 'ASSIGNMENT_CREATED',
    ASSIGNMENT_EDITED: 'ASSIGNMENT_EDITED',
    CLASS_EDITED: 'CLASS_EDITED'
    
}

class ConsoleMessage {
    constructor(user, messageType, userClassName, userAssignmentName) {
        this.user = user;
        this.messageType = messageType;
        this.userClassName = userClassName;
        this.userAssignmentName = userAssignmentName;
    }
}

class ConsoleEventNotifier {
    consoleEvents = [];
    handlers = [];

    constructor() {
        const userName = "Jefff@example.com";

        //Right here will simulate some console events for testing purposes.  In the future, these events will be generated by the server and sent to the client via websockets, but for now, I will just generate some fake events every few seconds to test that the event handling and display on the about page works correctly.
        setInterval(() => {
            const randomEventType = Object.values(ConsoleEvent)[Math.floor(Math.random() * Object.values(ConsoleEvent).length)];
            let userClassName = "MATH 210";
            let userAssignmentName = "Section 1 HW";
            this.broadcastEvent(userName, randomEventType, userClassName, userAssignmentName);
        }, 1000);
    }


    addHandler(handler) {
        this.handlers.push(handler);
    }

    removeHandler(handler) {
        this.handlers = this.handlers.filter((h) => h !== handler);
    }

    broadcastEvent(user, messageType, userClassName, userAssignmentName) {
        const consoleMessage = new ConsoleMessage(user, messageType, userClassName, userAssignmentName);
        this.consoleEvents.push(consoleMessage);
        this.handlers.forEach((handler) => handler(consoleMessage));
    }
}

const ConsoleNotifier = new ConsoleEventNotifier();
export {ConsoleMessage, ConsoleNotifier};